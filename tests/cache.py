#!/usr/bin/env python3
"""Real Nginx proxy-cache privacy checks in the disposable Ubuntu test image."""
import ast,http.server,pathlib,socket,subprocess,tempfile,threading,time,urllib.request,os
assert os.environ.get('CGPANEL_DISPOSABLE_TEST')=='1'
root=pathlib.Path(__file__).resolve().parents[1]
config_tree=ast.parse((root/'deploy/setup-v0.5.py').read_text())
maps=None
for node in ast.walk(config_tree):
 if isinstance(node,ast.Call) and isinstance(node.func,ast.Attribute) and node.func.attr=='write_text' and node.args and isinstance(node.args[0],ast.Constant) and str(node.args[0].value).startswith('proxy_cache_path'):maps=node.args[0].value
assert maps
class Origin(http.server.BaseHTTPRequestHandler):
 count=0
 def do_GET(self):
  Origin.count+=1;self.send_response(200)
  self.send_header('Cache-Control','private, max-age=60' if self.path=='/private' else 'public, max-age=60')
  if self.path=='/set-cookie':self.send_header('Set-Cookie','session=private; HttpOnly')
  self.send_header('Content-Length','2');self.end_headers();self.wfile.write(b'OK')
 def log_message(self,*args):pass
origin=http.server.ThreadingHTTPServer(('127.0.0.1',0),Origin);threading.Thread(target=origin.serve_forever,daemon=True).start()
with socket.socket() as s:s.bind(('127.0.0.1',0));port=s.getsockname()[1]
with tempfile.TemporaryDirectory() as folder:
 folder=pathlib.Path(folder);folder.chmod(0o755);cache=pathlib.Path('/var/cache/cgpanel-pages');cache.mkdir(exist_ok=True);cache.chmod(0o777)
 # Use the same directives generated by tls_agent, read directly from Rust's static string.
 import re
 text=(root/'src/tls_agent.rs').read_text()
 directives=next(value.replace('\\"','"') for value in re.findall(r'"((?:\\.|[^"\\])*)"',text) if value.startswith('proxy_cache cgp_pages;'))
 nginx=folder/'nginx.conf';nginx.write_text(f'pid {folder}/nginx.pid; error_log {folder}/error.log; events {{}} http {{ {maps} server {{listen 127.0.0.1:{port}; location / {{{directives} proxy_pass http://127.0.0.1:{origin.server_port};}}}}}}')
 subprocess.run(['nginx','-t','-c',str(nginx)],check=True,capture_output=True)
 process=subprocess.Popen(['nginx','-c',str(nginx),'-g','daemon off;'])
 try:
  time.sleep(.2)
  def get(path,headers=None):
   with urllib.request.urlopen(urllib.request.Request(f'http://127.0.0.1:{port}'+path,headers=headers or {})) as r:return r.headers.get('X-CGPanel-Cache')
  values=[get('/public') for _ in range(4)];assert values[-1]=='HIT',values
  for path in ['/private','/set-cookie']:
   values=[get(path) for _ in range(4)];assert 'HIT' not in values,(path,values)
  for headers in [{'Cookie':'login=secret'},{'Authorization':'Bearer secret'}]:
   values=[get('/public',headers) for _ in range(3)];assert values==['BYPASS']*3,values
  print('PASS: Nginx public-page HIT; cookie/auth requests BYPASS; private and Set-Cookie responses never cached')
 finally:process.terminate();process.wait(timeout=10);origin.shutdown()
